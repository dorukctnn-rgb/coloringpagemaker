// One-off import of the 30 Halloween pins (24 October 2026) as feed seeds and printable pages.
//
//   node cloudflare/autopin/tools/import-seeds.mjs <pins.json> <pages dir>
//
// pins.json is takip/devir/coloring-halloween-pins.json (title, description, alt text, release time for every pin) and
// <pages dir> holds the raw 1024 px coloring pages the pins were made from (takip/devir/coloring-halloween-pages).
// Writes cloudflare/autopin/seeds.js (the text), public/printables/img/<slug>.png (the printable page, whitened,
// 1024 x 1024 gray, with the "made by an image model" metadata) and <slug>-400.png (a 400 px thumbnail).
// The pin images themselves are the files already in public/pins/halloween-2026/.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { whiten, decodeGrayPng } from '../art.js';
import { encodePngGray, resizeGray, xmpChunk } from '../raster.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..', '..', '..');
const [pinsFile, pagesDir] = process.argv.slice(2);
if (!pinsFile || !pagesDir) { console.error('usage: node import-seeds.mjs <pins.json> <pages dir>'); process.exit(2); }

const pins = JSON.parse(fs.readFileSync(pinsFile, 'utf8'));
const imgDir = path.join(repo, 'public', 'printables', 'img');
fs.mkdirSync(imgDir, { recursive: true });
const firstSentence = s => { const m = /^(.+?[.!?])(\s|$)/.exec(s); return m ? m[1] : s; };

const seeds = [];
for (const p of pins.slice().sort((a, b) => a.order - b.order)) {
  const rawName = p.slug.replace(/-coloring-page$/, '') + '.png';
  const src = path.join(pagesDir, rawName);
  const img = decodeGrayPng(fs.readFileSync(src));
  if (img.w !== 1024 || img.h !== 1024) throw new Error(`${rawName} is ${img.w}x${img.h}`);
  const L = whiten(img.L);
  const meta = { title: p.on_image.headline, description: p.alt_text };
  fs.writeFileSync(path.join(imgDir, p.slug + '.png'), encodePngGray(L, 1024, 1024, { depth: 8, level: 9, extra: [xmpChunk(meta)] }));
  const thumb = resizeGray(L, 1024, 1024, 400, 400);
  fs.writeFileSync(path.join(imgDir, p.slug + '-400.png'), encodePngGray(thumb, 400, 400, { depth: 8, level: 9, extra: [xmpChunk(meta)] }));
  const pinFile = path.join(repo, 'public', 'pins', 'halloween-2026', p.slug + '.png');
  const pinBytes = fs.statSync(pinFile).size;
  seeds.push({
    order: p.order, slug: p.slug, theme: 'halloween', level: p.level,
    headline: p.on_image.headline, sub: p.on_image.subline,
    title: p.title, description: p.description, alt: p.alt_text, prompt: p.typed_prompt,
    intro: firstSentence(p.description),
    release: p.publish_utc.endsWith('Z') ? p.publish_utc : p.publish_utc + 'Z',
    pinBytes
  });
}
const header = [
  '// Generated by tools/import-seeds.mjs from the 30 Halloween pins of 24 October 2026. Do not edit by hand.',
  '// Each seed is a pin that is already hosted under /pins/halloween-2026/ and a printable page under /printables/img/.',
  'export const SEEDS = '
].join('\n');
fs.writeFileSync(path.join(repo, 'cloudflare', 'autopin', 'seeds.js'), header + JSON.stringify(seeds, null, 1) + ';\n');
console.log(`${seeds.length} seeds, first ${seeds[0].release}, last ${seeds[seeds.length - 1].release}`);
