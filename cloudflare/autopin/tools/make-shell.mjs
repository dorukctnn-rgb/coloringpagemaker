// Builds cloudflare/autopin/shell.js: the head assets, the navigation and the footer of the site as strings, so the
// Worker can wrap the printable pages in the same page shell as every other page. Run it again after a change to
// views/partials/head-assets.ejs, nav.ejs or footer.ejs (the test "the page shell matches views/partials" says when).
//
//   node cloudflare/autopin/tools/make-shell.mjs          writes shell.js
//   node cloudflare/autopin/tools/make-shell.mjs --check  exits 1 when shell.js is out of date
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..', '..', '..');
const require = createRequire(path.join(repo, 'package.json'));
const ejs = require('ejs');

export function shellSource() {
  const part = name => {
    const file = path.join(repo, 'views', 'partials', name + '.ejs');
    // git stores LF; this checkout may hold CRLF. The served pages are built from git, so use LF.
    const src = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
    return ejs.render(src, {}, { filename: file }).trim();
  };
  const shell = { headAssets: part('head-assets'), nav: part('nav'), footer: part('footer') };
  return '// Generated by tools/make-shell.mjs from views/partials (head-assets, nav, footer). Do not edit by hand.\n'
    + 'export const SHELL = ' + JSON.stringify(shell, null, 2) + ';\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.join(here, '..', 'shell.js');
  const next = shellSource();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (cur !== next) { console.error('shell.js is out of date: run node cloudflare/autopin/tools/make-shell.mjs'); process.exit(1); }
    console.log('shell.js is up to date');
  } else {
    fs.writeFileSync(out, next);
    console.log('wrote', out);
  }
}
